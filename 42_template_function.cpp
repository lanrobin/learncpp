#include <iostream>
#include <string>

/**
这是一个非常关键的追问！在前一个回答中，我提到了一条 C++ 的铁律：类模板既支持全特化也支持偏特化，但函数模板只支持全特化，绝对不支持偏特化！

为什么函数模板不支持偏特化？因为 C++ 之父 Bjarne Stroustrup 和标准委员会认为，函数已经拥有一种非常强大的机制来处理不同类型的参数了，那就是——函数重载（Function Overloading）。引入函数偏特化不仅多此一举，还会让编译器的匹配规则变得极其复杂和难以维护。

因此，在处理函数模板的“特殊情况”时，我们通常面临三种选择的博弈：主模板 vs 全特化 vs 模板重载 vs 普通函数。

下面我通过一个详细的代码示例，带你看看这四个角色在一起时，编译器是如何进行“选妃”的：


对于函数，不要写全特化，直接写普通函数的重载！
*/

// ============================================================================
// 1 号选手：主模板 (Primary Template)
// 地位：兜底方案。如果实在找不到更特殊的，就用它。
// ============================================================================
template <typename T>
void printValue(T val) {
    std::cout << "[1. 主模板]       处理通用类型: T = " << typeid(T).name() << "\n";
}

// ============================================================================
// 2 号选手：模板重载 (Template Overload)
// 地位：高级备胎。它是主模板的平级兄弟，只是长得更像某种特征（比如指针）。
// ============================================================================
template <typename T>
void printValue(T* val) {
    std::cout << "[2. 模板重载]     专门处理指针类型 (T*)\n";
}

// ============================================================================
// 3 号选手：主模板的全特化 (Full Specialization)
// 地位：隐藏的定制款。只有当编译器决定使用【1号主模板】且 T 为 int 时，它才会被触发。
// ============================================================================
template <>
void printValue<int>(int val) {
    std::cout << "[3. 全特化]       专门处理 int 的全特化版本\n";
}

// ============================================================================
// 4 号选手：普通非模板函数 (Non-template Function)
// 地位：皇亲国戚，霸道总裁。只要类型精确匹配，它拥有绝对的最高优先级！
// ============================================================================
void printValue(int val) {
    std::cout << "[4. 普通函数]     亲生的非模板函数，专门处理 int\n";
}

void printValue(double val) {
    std::cout << "[4. 普通函数]     亲生的非模板函数，专门处理 double\n";
}


// ============================================================================
// 测试主函数：见证编译器的“选妃”过程
// ============================================================================
int main() {
    std::cout << "========== 场景 A：无竞争者的兜底 ==========\n";
    std::string str = "Hello C++";
    // 候选：1号主模板
    // 结果：毫无悬念，只有 1 号能接纳 std::string。
    printValue(str); 


    std::cout << "\n========== 场景 B：普通函数降维打击 (碾压特化) ==========\n";
    // 传入 int。
    // 候选 1：4号普通函数 (需要 int)
    // 候选 2：1号主模板 (推导为 int)
    // 规则：普通函数与模板实例完全匹配时，普通函数绝对胜出！
    // 结果：4 号普通函数赢了。3 号全特化连出场的机会都没有。
    printValue(42); 


    std::cout << "\n========== 场景 C：如何强行召唤全特化？ ==========\n";
    // 如果我们就是想用 3 号全特化怎么办？
    // 必须加上尖括号 <int>，强行把 4号普通函数 踢出候选名单！
    // 候选：只有 1号主模板。
    // 编译器选中 1号 主模板后，进一步发现 1号 有一个针对 int 的全特化（3号）。
    // 结果：最终调用 3 号全特化。
    printValue<int>(42); 


    std::cout << "\n========== 场景 D：模板重载 vs 主模板 ==========\n";
    int x = 10;
    // 传入 int*。
    // 候选 1：1号主模板 (推导 T 为 int*)
    // 候选 2：2号模板重载 (推导 T 为 int)
    // 规则：2号 (T*) 比 1号 (T) 更具体，更贴近指针的本质。
    // 结果：2 号模板重载胜出。
    printValue(&x); 


    std::cout << "\n========== 场景 E：隐式转换陷阱 ==========\n";
    float f = 3.14f;
    // 传入 float。
    // 候选 1：1号主模板 (推导 T 为 float) -> 精确匹配
    // 候选 2：4号普通函数 (需要 double) -> 需要将 float 提升为 double
    // 规则：模板可以进行精确推导，不需要类型转换；而调用普通函数需要进行类型提升。
    // 【陷阱】：普通函数的特权仅限于“精确匹配”。如果需要转换，精确匹配的模板会反杀！
    // 结果：1 号主模板胜出！
    printValue(f); 

    return 0;
}