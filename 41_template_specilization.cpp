#include <iostream>
#include <string>
#include <vector>

/**
在写泛型代码时，我们通常会写一个可以处理所有类型的“通用版本”。但有时候，某些特定类型（比如指针、int、或是某种自定义的容器）需要一种完全不同、或者更高效的处理逻辑。这时候，我们就需要用到特化。

为了彻底搞懂它，我们要牢记三个概念：

主模板（泛化版本，Primary Template）：兜底方案，什么类型都能接。

全特化（Full Specialization）：为某一个绝对具体的类型（如 int, char*）量身定制的方案。

偏特化（Partial Specialization）：为某一类特征的类型（如所有的指针 T*，所有的引用 T&，或多个模板参数中固定了其中一部分）量身定制的方案。

⚠️ 一个极其重要的 C++ 铁律（面试必考）：
类模板（Class Template） 既支持全特化，也支持偏特化。
函数模板（Function Template） 只支持全特化，绝对不支持偏特化！（如果需要类似函数偏特化的功能，请直接使用普通的函数重载）。
*/

// ============================================================================
// 1. 主模板 (Primary Template) —— 泛化版本
// 作用：如果没有更匹配的特化版本，编译器就会退而求其次使用这个兜底版本。
// ============================================================================
template <typename T>
struct TypePrinter {
    static void print() {
        std::cout << "[主模板]   这是一个普通类型 (兜底方案)\n";
    }
};

// ============================================================================
// 2. 全特化 (Full Specialization)
// 语法：template <> (尖括号里什么都不写，说明没有未知的泛型参数了)
// 作用：精确狙击某个具体的类型。
// ============================================================================

// 全特化版本 1：专门针对 int
template <>
struct TypePrinter<int> {
    static void print() {
        std::cout << "[全特化]   这是一个绝对具体的 int 类型\n";
    }
};

// 全特化版本 2：专门针对 double
template <>
struct TypePrinter<double> {
    static void print() {
        std::cout << "[全特化]   这是一个绝对具体的 double 类型\n";
    }
};

// ============================================================================
// 3. 偏特化 (Partial Specialization)
// 语法：template <typename T> (还需要推导 T)，但在类名后加上特征限制，如 <T*>
// 作用：狙击“某一类”类型，范围比主模板小，但比全特化大。
// ============================================================================

// 偏特化版本 1：专门针对 所有的原生指针 (T*)
template <typename T>
struct TypePrinter<T*> {
    static void print() {
        // T 已经被剥离了指针符号，代表指针指向的底层类型
        std::cout << "[偏特化 1] 这是一个指针类型 (T*)\n";
    }
};

// 偏特化版本 2：专门针对 所有的引用 (T&)
template <typename T>
struct TypePrinter<T&> {
    static void print() {
        std::cout << "[偏特化 2] 这是一个左值引用类型 (T&)\n";
    }
};

// 偏特化版本 3：专门针对 所有的标准库 vector (std::vector<T>)
// 提取出了容器内部的类型 T
template <typename T>
struct TypePrinter<std::vector<T>> {
    static void print() {
        std::cout << "[偏特化 3] 这是一个 std::vector 容器\n";
    }
};

// ============================================================================
// 4. 偏特化的“内卷” (特化程度越高越优先)
// ============================================================================

// 偏特化版本 4：专门针对 二级指针 (T**)
// 注意：T** 也是一种指针，它按理说也能匹配偏特化 1 (T*)。
// 但是 C++ 的匹配规则是：【谁最特殊，谁就赢】。
template <typename T>
struct TypePrinter<T**> {
    static void print() {
        std::cout << "[偏特化 4] 这是一个二级指针 (T**)，比 T* 更特殊！\n";
    }
};


// ============================================================================
// 测试主函数
// ============================================================================
int main() {
    std::cout << "========== 场景 A：主模板与全特化 ==========\n";
    
    // std::string 没有对应的特化版本，老老实实走主模板兜底
    TypePrinter<std::string>::print(); 
    
    // int 被全特化 1 精确狙击
    TypePrinter<int>::print();         

    std::cout << "\n========== 场景 B：偏特化 (范围缩小) ==========\n";
    
    // float* 是个指针。
    // 候选：主模板 <T> 和 偏特化 <T*>。
    // <T*> 比 <T> 限制更严、更特化，赢家：偏特化 1
    TypePrinter<float*>::print();      

    // double& 是个引用。
    // 赢家：偏特化 2
    TypePrinter<double&>::print();     

    // std::vector<int> 匹配到了专门为 vector 写的偏特化版本
    TypePrinter<std::vector<int>>::print(); 

    std::cout << "\n========== 场景 C：特化程度的终极较量 ==========\n";
    
    // 【编译器内心的激烈搏杀】：
    // 目标类型是 char** (指向指针的指针)
    // 候选 1：主模板 <T> (T 推导为 char**)
    // 候选 2：偏特化 <T*> (T 推导为 char*)
    // 候选 3：偏特化 <T**> (T 推导为 char)
    // 规则：特化程度越高（越接近原貌，受限越严格），优先级越高。
    // <T**> 显然比 <T*> 更具体、更特殊。
    // 赢家：偏特化 4
    TypePrinter<char**>::print();      

    // 【高频陷阱】：int* 会匹配什么？
    // 注意，我们上面有 <int> 的全特化，也有 <T*> 的偏特化。
    // int* 是指针，<int> 根本管不到指针，所以它只能匹配 <T*> 偏特化！
    TypePrinter<int*>::print();

    return 0;
}

/*
当编译器在处理类型 TargetType 并尝试实例化模板时，它会遵循以下严密的层级过滤顺序（从严到宽）：

第一梯队（找全特化）：有没有哪个 template <> struct 后面的尖括号内容，和当前的 TargetType 一模一样？如果有，直接录用它，匹配结束。

第二梯队（找最匹配的偏特化）：如果没有全特化，看看有没有哪个偏特化的模式（比如 <T*> 或 <T&>）能套在 TargetType 上。

如果只有一个偏特化能套上，录用它。

如果有多个偏特化都能套上（比如二级指针匹配了 <T*> 和 <T**>），比较哪一个的“模式”更具体、更狭窄。越具体的赢。

如果有多个偏特化都能套上，且特化程度完全一样（谁也说服不了谁），编译器直接报错（歧义，Ambiguous class template instantiation）。

第三梯队（找主模板）：如果没有任何特化版本能匹配，最后只能老老实实退回到泛化的主模板。

这种机制是 C++ 标准库（STL）中类型萃取（Type Traits）（比如 std::remove_reference, std::is_pointer 等）能够运作的绝对基石。通过偏特化剥离出 T* 或 T& 中的 T，编译器就能在编译期拥有“透视”类型的能力。
*/